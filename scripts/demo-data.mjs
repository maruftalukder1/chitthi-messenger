#!/usr/bin/env node
/**
 * demo-data.mjs — Chitthi DEMO dataset generator (Phase 5 packaging).
 *
 * Writes a clearly-labelled DEMO store.json (plus a DEMO_DATASET.txt marker)
 * into the TARGET directory passed as the first argument:
 *
 *   node scripts/demo-data.mjs <target-dir>
 *
 * Then run the server against it, e.g.:
 *
 *   CHITTHI_DATA_DIR=<target-dir> CHITTHI_ALLOW_UNAUTH_DEMO=true npm run dev
 *
 * Safety:
 * - Uses only Node.js builtins. No dependencies.
 * - REFUSES to write into the repository's own data/ directory
 *   (<repo>/data), so the shipped pristine snapshot can never be
 *   overwritten by this script. The check runs BEFORE any write.
 * - Every user, channel and story name in the dataset is prefixed
 *   with "Demo", and the snapshot carries a top-level `_demoDataset`
 *   marker record. A fresh install NEVER contains this data — the
 *   shipped data/store.json is the empty snapshot.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, '..');
const repoDataDir = path.join(repoRoot, 'data');

const targetArg = process.argv[2];
if (!targetArg) {
  console.error('Usage: node scripts/demo-data.mjs <target-dir>');
  console.error('The directory will be created if it does not exist.');
  process.exit(2);
}

const targetDir = path.resolve(process.cwd(), targetArg);

// --- Refuse-path: never touch the repo's own data/ dir (checked first). ---
if (targetDir === repoDataDir || targetDir.startsWith(repoDataDir + path.sep)) {
  console.error(
    `Refusing to write demo data into the repository data directory (${repoDataDir}).`
  );
  console.error('Choose a different target directory, e.g. /tmp/chitthi-demo-data');
  process.exit(1);
}

const now = Date.now();
const HOUR = 60 * 60 * 1000;
const MIN = 60 * 1000;

// --- Demo identities (every display name is prefixed "Demo") --------------
const alice = {
  id: 'demo_alice',
  name: 'Demo Alice',
  username: 'demo_alice',
  avatar: '',
  about: 'Demo account — sample data only, not a real person.',
  mood: '',
  discoverable: true,
  privacy: { photo: 'everyone', about: 'everyone', lastSeen: 'everyone', findMe: 'everyone', groupAdd: 'everyone' },
};
const bob = {
  id: 'demo_bob',
  name: 'Demo Bob',
  username: 'demo_bob',
  avatar: '',
  about: 'Demo account — sample data only, not a real person.',
  mood: '',
  discoverable: true,
  privacy: { photo: 'everyone', about: 'everyone', lastSeen: 'everyone', findMe: 'everyone', groupAdd: 'everyone' },
};

// DM room id convention (server.ts / PHASE0_REPORT.md): sorted ids joined by "__".
const dmRoomId = [alice.id, bob.id].sort().join('__');
const groupId = 'demo_group';

function msg(id, sender, roomId, content, ts, extra = {}) {
  return {
    id,
    senderId: sender.id,
    senderName: sender.name,
    senderAvatar: '',
    roomId,
    type: 'text',
    content,
    timestamp: ts,
    deliveredTo: [alice.id, bob.id],
    readBy: [alice.id, bob.id],
    ...extra,
  };
}

const groupChannel = {
  id: groupId,
  name: 'Demo Group Chat',
  description: 'Demo group — sample data only.',
  iconType: 'general',
  isGroup: true,
  ownerId: alice.id,
  memberIds: [alice.id, bob.id],
  adminIds: [alice.id],
  membersCount: 2,
  sections: [
    { id: 'general', name: 'general', description: 'Demo general section' },
    { id: 'announcements', name: 'announcements', description: 'Demo announcements', readOnly: true },
  ],
  createdAt: now - 2 * HOUR,
  lastMessage: 'Demo Bob: Welcome to the demo group!',
  lastMessageTimestamp: now - 5 * MIN,
};

const dmMessages = [
  msg('demo_msg_dm_1', alice, dmRoomId, 'Demo message: Hi Bob, this is sample demo data.', now - 30 * MIN),
  msg('demo_msg_dm_2', bob, dmRoomId, 'Demo message: Hi Alice — demo reply, not a real conversation.', now - 28 * MIN),
  msg('demo_msg_dm_3', alice, dmRoomId, 'Demo message: Try starring, searching or exporting this chat.', now - 25 * MIN),
];

const groupMessages = [
  msg('demo_msg_grp_1', alice, groupId, 'Demo message: Welcome to the demo group!', now - 10 * MIN, { sectionId: 'general' }),
  msg('demo_msg_grp_2', bob, groupId, 'Demo Bob: Welcome to the demo group!', now - 5 * MIN, { sectionId: 'general' }),
];

const demoStory = {
  id: 'demo_story_1',
  userId: alice.id,
  userName: alice.name,
  userAvatar: '',
  media: '',
  type: 'text',
  kind: 'text',
  textData: { text: 'Demo story — sample only', bg: '#2563EB', font: 'default' },
  audience: { mode: 'everyone' },
  reactions: [],
  createdAt: now - 1 * HOUR,
  expiresAt: now + 23 * HOUR,
  viewers: [{ userId: bob.id, viewedAt: now - 30 * MIN }],
};

const snapshot = {
  // Marker record: this snapshot is DEMO data, generated by
  // scripts/demo-data.mjs. The server loader ignores unknown keys.
  _demoDataset: {
    demo: true,
    label: 'DEMO DATA — generated by scripts/demo-data.mjs. Not real users or conversations.',
    generatedAt: now,
    users: [alice.id, bob.id],
  },
  version: 1,
  savedAt: now,
  channels: [groupChannel],
  messages: {
    [dmRoomId]: dmMessages,
    [groupId]: groupMessages,
  },
  stories: [demoStory],
  blocks: {},
  reports: [],
  directory: [alice, bob],
  usernames: { demo_alice: alice.id, demo_bob: bob.id },
  releasedHandles: {},
  scheduled: [],
  reminders: [],
  stars: {},
  callLogs: {},
  storyMutes: {},
  highlights: {},
  seenDevices: {},
  userLastSeen: {},
  userEmails: {},
};

fs.mkdirSync(targetDir, { recursive: true });
const storePath = path.join(targetDir, 'store.json');
fs.writeFileSync(storePath, JSON.stringify(snapshot, null, 2) + '\n', 'utf8');
fs.writeFileSync(
  path.join(targetDir, 'DEMO_DATASET.txt'),
  [
    'DEMO DATA — generated by scripts/demo-data.mjs',
    'Every name in store.json is prefixed "Demo". These are not real users.',
    'A fresh Chitthi install never contains this data.',
    `Generated: ${new Date(now).toISOString()}`,
    '',
  ].join('\n'),
  'utf8'
);

console.log(`Demo dataset written to ${storePath}`);
console.log('Run the server with:');
console.log(`  CHITTHI_DATA_DIR=${targetDir} CHITTHI_ALLOW_UNAUTH_DEMO=true npm run dev`);
console.log('See docs/DEMO_DATA.md for details.');
